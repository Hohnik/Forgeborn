"""Builds the API fixtures from Blizzard's UI source for WoW Forever:
tests/fixtures/forever_widgets.lua (widget methods, for the test mock) and
tools/apicheck/forever_api.txt.gz (everything else, for check_api.py).

The fixture lists what really exists in the Forever client, so the tests can reject anything else:
widget methods per widget class, global API functions, C_ namespace functions, Blizzard Lua globals,
XML templates, font objects, atlases used by Blizzard XML and SOUNDKIT names.

    git clone --depth 1 --branch forever https://github.com/Gethe/wow-ui-source
    python3 tools/apicheck/gen_fixture.py path/to/wow-ui-source/Interface/AddOns
"""
import gzip
import os
import re
import sys

root = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
widget_path = os.path.join(here, "..", "..", "tests", "fixtures", "forever_widgets.lua")
api_path = os.path.join(here, "forever_api.txt.gz")
docs = os.path.join(root, "Blizzard_APIDocumentationGenerated")

widget = {}      # doc table name -> set of method names (ScriptObject docs)
namespaces = {}  # C_Foo -> set of functions
global_funcs = set()
events = set()

table_re = re.compile(r'^local\s+(\w+)\s*=\s*$', re.M)
for name in sorted(os.listdir(docs)):
    if not name.endswith(".lua"):
        continue
    text = open(os.path.join(docs, name), encoding="utf-8", errors="replace").read()
    ns_match = re.search(r'^\tNamespace = "(\w+)"', text, re.M)
    type_match = re.search(r'^\tType = "(\w+)"', text, re.M)
    table_name = re.search(r'^\tName = "(\w+)"', text, re.M)
    funcs_block = re.search(r'^\tFunctions =\s*\{(.*?)^\t\},', text, re.M | re.S)
    funcs = set(re.findall(r'^\t\t\{\s*\n\t\t\tName = "(\w+)",\s*\n\t\t\tType = "Function"', funcs_block.group(1), re.M)) if funcs_block else set()
    for ev in re.findall(r'LiteralName = "(\w+)"', text):
        events.add(ev)
    if type_match and type_match.group(1) == "ScriptObject" and table_name:
        widget[table_name.group(1)] = funcs
    elif ns_match:
        namespaces.setdefault(ns_match.group(1), set()).update(funcs)
    else:
        global_funcs.update(funcs)

lua_globals = set()
textures = set()     # texture paths Blizzard's Lua and XML use (lowercase, backslashes)
called = set()       # global names Blizzard's own Lua calls (C functions the docs leave out, like GetLootSlotLink)
referenced = set()   # capitalised names Blizzard's Lua reads (global strings like YES, UIParent, SlashCmdList)
templates = set()
fonts = set()
atlases = set()
func_re = re.compile(r'^function\s+([A-Za-z_][\w]*)\s*\(', re.M)
assign_re = re.compile(r'^([A-Z][A-Za-z0-9_]*)\s*=', re.M)
for dirpath, _, files in os.walk(root):
    for f in files:
        path = os.path.join(dirpath, f)
        if f.endswith(".lua") or f.endswith(".xml"):
            raw = open(path, encoding="utf-8", errors="replace").read()
            for t in re.findall(r'Interface(?:\\\\|\\|/)[A-Za-z0-9_\-\\/]+', raw):
                textures.add(re.sub(r'[\\/]+', lambda _: '\\', t).lower())
        if f.endswith(".lua"):
            text = open(path, encoding="utf-8", errors="replace").read()
            lua_globals.update(func_re.findall(text))
            lua_globals.update(assign_re.findall(text))
            code = re.sub(r'--[^\n]*', '', text)
            called.update(re.findall(r'(?<![\w.:])([A-Z][A-Za-z0-9_]*)\s*\(', code))
            code = re.sub(r'"(?:[^"\\\n]|\\.)*"', '""', code)
            referenced.update(re.findall(r'(?<![\w.:])([A-Z][A-Za-z0-9_]*)\b', code))
        elif f.endswith(".xml"):
            text = open(path, encoding="utf-8", errors="replace").read()
            for m in re.finditer(r'<(\w+)\s([^>]*?)\bname="([\w$]+)"([^>]*)>', text):
                tag, before, name, after = m.groups()
                rest = before + after
                if 'virtual="true"' in rest:
                    templates.add(name)
                if tag in ("Font", "FontFamily"):
                    fonts.add(name)
                elif "$" not in name and 'virtual="true"' not in rest:
                    lua_globals.add(name)
            atlases.update(re.findall(r'atlas="([\w\-]+)"', text))
            atlases.update(re.findall(r'key="\w*[Aa]tlas\w*" value="([\w\-]+)"', text))

soundkit = set()
sk = open(os.path.join(root, "Blizzard_SharedXML", "Mainline", "SoundKitConstants.lua"), encoding="utf-8").read()
soundkit.update(re.findall(r'^\t(\w+)\s*=\s*\d+', sk, re.M))

def lua_set(name, values):
    items = ",".join('["%s"]=true' % v for v in sorted(values))
    return "%s = {%s},\n" % (name, items)

version_file = os.path.join(root, "..", "..", "version.txt")
version = open(version_file).read().strip() if os.path.exists(version_file) else "?"

# Widget methods for the test mock (small, Lua).
with open(widget_path, "w", encoding="utf-8") as out:
    out.write("-- Generated by tools/apicheck/gen_fixture.py from Blizzard's UI source for WoW Forever %s. Do not edit.\n" % version)
    out.write("-- Methods of each widget class (and the SOUNDKIT names), so the test mock can reject what the client doesn't have.\n")
    out.write("return {\n")
    for name in sorted(widget):
        out.write("  " + lua_set(name, widget[name]))
    out.write("  " + lua_set("__soundkit", soundkit))
    out.write("}\n")

# Everything else for check_api.py (one "section name" per line, gzip).
with gzip.open(api_path, "wt", encoding="utf-8") as out:
    out.write("version %s\n" % version)
    def section(name, values):
        for v in sorted(values):
            out.write("%s %s\n" % (name, v))
    for ns_name, funcs in namespaces.items():
        section("namespace", [ns_name])
        section("ns:" + ns_name, funcs)
    section("globalFunctions", global_funcs)
    section("luaGlobals", lua_globals)
    section("calledGlobals", called)
    section("referencedGlobals", referenced)
    section("templates", templates)
    section("fonts", fonts)
    section("atlases", atlases)
    section("soundkit", soundkit)
    section("events", events)
    section("textures", textures)
print("wrote", widget_path, "and", api_path)
print("widget tables:", len(widget), "namespaces:", len(namespaces), "global funcs:", len(global_funcs),
      "lua globals:", len(lua_globals), "templates:", len(templates), "fonts:", len(fonts), "sounds:", len(soundkit), "events:", len(events))
