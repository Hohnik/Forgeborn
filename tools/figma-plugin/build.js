// Makes the Figma plugin's code.js (the layout editor's core + UI/Layout.lua + main.js) and forgeborn-window.svg.
// Run after changing UI/Layout.lua, tools/layout-editor/index.html or main.js:
//
//     node tools/figma-plugin/build.js            (writes the files)
//     node tools/figma-plugin/build.js --check    (fails if they are out of date)
"use strict";
const fs = require("fs");
const path = require("path");

const here = __dirname;
const root = path.join(here, "..", "..");
const html = fs.readFileSync(path.join(root, "tools", "layout-editor", "index.html"), "utf8");
const core = html.match(/<script id="core">\n([\s\S]*?)<\/script>/)[1];
const lua = fs.readFileSync(path.join(root, "UI", "Layout.lua"), "utf8");
const main = fs.readFileSync(path.join(here, "main.js"), "utf8");

const code = "// Generated by tools/figma-plugin/build.js from tools/layout-editor/index.html (core), UI/Layout.lua and main.js.\n"
	+ "// Do not edit: change those files and run the build again.\n"
	+ core + "\nvar DEFAULT_LUA = " + JSON.stringify(lua) + ";\n\n" + main;

const C = { exports: {} };
new Function("module", core)(C);
const { KEYS, SIZES, BY_KEY, fromLua, toSVG } = C.exports;
const empty = {};
for (const k of KEYS) empty[k] = new Array(SIZES[BY_KEY[k].kind]).fill(0);
const svg = toSVG(fromLua(lua, empty).values, "en", 4);

const outputs = { "code.js": code, "forgeborn-window.svg": svg };
let stale = [];
for (const [name, text] of Object.entries(outputs)) {
	const file = path.join(here, name);
	const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
	if (old === text) continue;
	if (process.argv.includes("--check")) stale.push(name);
	else {
		fs.writeFileSync(file, text);
		console.log("wrote tools/figma-plugin/" + name);
	}
}
if (stale.length) {
	console.error("out of date: " + stale.join(", ") + " (run node tools/figma-plugin/build.js)");
	process.exit(1);
}
